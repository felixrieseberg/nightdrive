  static func headUnitGlyph(_ character: Character) -> [UInt8]? {
    headUnitOverrides[character] ?? glyphs[character]
  }

  static func width(of text: String) -> Int {
    let count = text.count
    guard count > 0 else { return 0 }
    return count * (glyphWidth + tracking) - tracking
  }

  static let blank: [UInt8] = [0, 0, 0, 0, 0]

  static func glyph(_ character: Character) -> [UInt8] {
    let upper = String(character).uppercased().first ?? " "
    return glyphs[upper] ?? blank
  }

  static func column(_ character: Character, _ column: Int) -> UInt8 {
    guard column >= 0, column < glyphWidth else { return 0 }
    return glyph(character)[column]
  }

  static func isLit(_ text: String, x: Int, y: Int) -> Bool {
    guard y >= 0, y < glyphHeight, x >= 0 else { return false }
    let stride = glyphWidth + tracking
    let index = x / stride
    let column = x % stride
    guard column < glyphWidth else { return false }
    let characters = Array(text)
    guard index < characters.count else { return false }
    return glyph(characters[index])[column] & (1 << UInt8(y)) != 0
  }
